def drop_sections(css, names):
    # Remove numbered design-system sections (e.g. "5. Backgrounds") up to the next section header.
    parts = re.split(r'(/\* ─+ *\d+\.[^*]*\*/)', css)
    out, skip = [], False
    for p in parts:
        m = re.match(r'/\* ─+ *(\d+)\.', p)
        if m: skip = int(m.group(1)) in names
        if not skip: out.append(p)
    return ''.join(out)

def hoist_keyframes(css):
    """@keyframes can't live inside a nested rule; pull them out to top level."""
    out, frames, i = [], [], 0
    while True:
        j = css.find('@keyframes', i)
        if j < 0: out.append(css[i:]); break
        out.append(css[i:j])
        k = css.index('{', j); depth = 0
        while True:
            if css[k] == '{': depth += 1
            elif css[k] == '}':
                depth -= 1
                if depth == 0: break
            k += 1
        frames.append(css[j:k + 1]); i = k + 1
    return ''.join(out), '\n'.join(frames)

def scoped(css):
    body, frames = hoist_keyframes(css)
    return frames + '\n.app-legacy {\n' + body + '\n}\n'

